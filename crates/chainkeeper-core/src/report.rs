//! Report types returned by service operations and rendered by the CLI.

use std::path::PathBuf;

use serde::{Deserialize, Serialize};
use time::OffsetDateTime;

use crate::config::AuthorityKind;
use crate::ids::{AuthorityName, TenantId};
use crate::records::{
    CertificateRecord, CertificateStatus, CrlRecord, IndexStats, RevocationRecord,
};

/// Report for `ck init`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InitReport {
    /// Tenant identifier written to `tenant.yaml`.
    pub tenant_id: TenantId,
    /// Repository root.
    pub root: PathBuf,
    /// Paths created by the command.
    pub created_paths: Vec<PathBuf>,
    /// Commit produced by the command.
    pub commit: Option<String>,
}

/// Report for `ck issue`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct IssueReport {
    /// Issued certificate metadata.
    pub certificate: CertificateRecord,
    /// Repository-relative path of the PEM certificate.
    pub cert_path: PathBuf,
    /// Destination of the generated private key, when one was written.
    pub key_path: Option<PathBuf>,
    /// Commit produced by the command.
    pub commit: Option<String>,
}

/// Report for `ck revoke`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RevokeReport {
    /// Revocation metadata.
    pub revocation: RevocationRecord,
    /// CRL regenerated by the revocation.
    pub crl: Option<CrlRecord>,
    /// Commit produced by the command.
    pub commit: Option<String>,
}

/// Report for `ck inspect`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct InspectReport {
    /// Certificate metadata.
    pub certificate: CertificateRecord,
    /// Lifecycle status at inspection time.
    pub status: CertificateStatus,
    /// PEM certificate contents, when loaded.
    pub cert_pem: Option<String>,
    /// PEM chain contents, when loaded.
    pub chain_pem: Option<String>,
}

/// Trust hierarchy node.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TreeNode {
    /// Authority name.
    pub name: AuthorityName,
    /// Authority kind.
    pub kind: AuthorityKind,
    /// Validity end of the authority certificate, when known.
    #[serde(
        default,
        skip_serializing_if = "Option::is_none",
        with = "crate::time_util::seconds_option"
    )]
    pub expires_at: Option<OffsetDateTime>,
    /// Child authorities.
    pub children: Vec<Self>,
}

/// Report for `ck tree`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TreeReport {
    /// Root authorities.
    pub roots: Vec<TreeNode>,
}

/// Kind of analysis performed by `ck analyze`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[non_exhaustive]
pub enum AnalyzeKind {
    /// Certificates approaching expiry.
    #[serde(rename = "expirations")]
    Expirations,
    /// Revocation statistics.
    #[serde(rename = "revocations")]
    Revocations,
    /// Intermediate authority health.
    #[serde(rename = "intermediates")]
    Intermediates,
    /// Algorithm distribution.
    #[serde(rename = "algorithms")]
    Algorithms,
    /// Policy compliance.
    #[serde(rename = "policy")]
    Policy,
}

/// Severity attached to a finding.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[non_exhaustive]
pub enum Severity {
    /// Informational finding.
    #[serde(rename = "info")]
    Info,
    /// Finding that needs attention soon.
    #[serde(rename = "warning")]
    Warning,
    /// Finding that needs attention now.
    #[serde(rename = "error")]
    Error,
}

/// Single analysis finding.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AnalysisFinding {
    /// Stable finding code.
    pub code: String,
    /// Finding severity.
    pub severity: Severity,
    /// Human readable message.
    pub message: String,
    /// Identifier of the affected object, if any.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub object_id: Option<String>,
}

/// Report for `ck analyze <kind>`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AnalyzeReport {
    /// Analysis performed.
    pub kind: AnalyzeKind,
    /// Analysis time.
    #[serde(with = "crate::time_util::seconds")]
    pub generated_at: OffsetDateTime,
    /// Findings, ordered by severity then object id.
    pub findings: Vec<AnalysisFinding>,
}

/// Single doctor finding.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct DoctorFinding {
    /// Stable finding code.
    pub code: String,
    /// Finding severity.
    pub severity: Severity,
    /// Human readable message.
    pub message: String,
    /// Identifier of the affected object, if any.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub object_id: Option<String>,
}

/// Report for `ck doctor`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct DoctorReport {
    /// Whether no `Error` finding was reported.
    pub healthy: bool,
    /// Check time.
    #[serde(with = "crate::time_util::seconds")]
    pub checked_at: OffsetDateTime,
    /// Findings, ordered by severity then object id.
    pub findings: Vec<DoctorFinding>,
}

/// Report for `ck diff`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct DiffReport {
    /// Start commit used for the comparison.
    pub from: Option<String>,
    /// End commit used for the comparison.
    pub to: Option<String>,
    /// Paths added between the commits.
    pub added: Vec<PathBuf>,
    /// Paths modified between the commits.
    pub modified: Vec<PathBuf>,
    /// Paths removed between the commits.
    pub removed: Vec<PathBuf>,
}

/// Report for `ck index rebuild`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct IndexReport {
    /// Rebuild time.
    #[serde(with = "crate::time_util::seconds")]
    pub generated_at: OffsetDateTime,
    /// Schema version written to the index.
    pub schema_version: u32,
    /// Row counts written to the index.
    pub stats: IndexStats,
}

#[cfg(test)]
mod tests {
    use time::macros::datetime;

    use super::{DoctorFinding, DoctorReport, Severity};

    #[test]
    fn doctor_report_is_serialisable() {
        let report = DoctorReport {
            healthy: false,
            checked_at: datetime!(2024-05-01 12:00:00 UTC),
            findings: vec![DoctorFinding {
                code: "CRL_MISSING".to_owned(),
                severity: Severity::Error,
                message: "no CRL for authority tls".to_owned(),
                object_id: Some("tls".to_owned()),
            }],
        };
        let json = serde_json::to_string(&report).expect("serialisable");
        let parsed: DoctorReport = serde_json::from_str(&json).expect("round trip");
        assert_eq!(report, parsed);
    }
}
